-- ----------------------------------------------------------------------------
-- Storage: bucket público "bandeiras", onde a tela "Bandeiras" do app faz
-- upload dos PNGs das bandeiras novas. Público porque a imagem é exibida
-- via <img src> puro (sem header de autenticação) nas telas de Calendário
-- e Classificação Geral — mesmo trade-off de exposição que a anon key/URL
-- do projeto já têm hoje (ver comentário em 0002_policies_anon.sql).
-- ----------------------------------------------------------------------------
insert into storage.buckets (id, name, public)
values ('bandeiras', 'bandeiras', true)
on conflict (id) do nothing;

drop policy if exists bandeiras_leitura_publica on storage.objects;
create policy bandeiras_leitura_publica
  on storage.objects for select
  to public
  using (bucket_id = 'bandeiras');

drop policy if exists bandeiras_escrita_autenticado on storage.objects;
create policy bandeiras_escrita_autenticado
  on storage.objects for insert
  to authenticated
  with check (bucket_id = 'bandeiras');

drop policy if exists bandeiras_update_autenticado on storage.objects;
create policy bandeiras_update_autenticado
  on storage.objects for update
  to authenticated
  using (bucket_id = 'bandeiras')
  with check (bucket_id = 'bandeiras');

drop policy if exists bandeiras_delete_autenticado on storage.objects;
create policy bandeiras_delete_autenticado
  on storage.objects for delete
  to authenticated
  using (bucket_id = 'bandeiras');
