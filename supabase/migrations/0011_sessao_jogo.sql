-- Rascunho das sessões enviadas pelo jogo (telemetria UDP) via bridge local.
-- NÃO alimenta a classificação: serve só para o botão "Importar do jogo" da
-- tela Prova a Prova preencher o formulário. Quem grava em tb_resultado
-- continua sendo você, ao clicar em Salvar.
create table if not exists f1.tb_sessao_jogo (
  id           bigint generated by default as identity primary key,
  session_uid  text    not null,
  session_type integer not null,
  track_id     integer,
  payload      jsonb   not null,
  created_at   timestamptz not null default now(),
  unique (session_uid, session_type)
);

comment on table f1.tb_sessao_jogo is 'Classificação final de cada sessão enviada pelo jogo (rascunho para importar na Prova a Prova).';

create index if not exists idx_tb_sessao_jogo_created on f1.tb_sessao_jogo (created_at desc);

alter table f1.tb_sessao_jogo enable row level security;
drop policy if exists auth_all_tb_sessao_jogo on f1.tb_sessao_jogo;
create policy auth_all_tb_sessao_jogo on f1.tb_sessao_jogo for all to authenticated using (true) with check (true);
grant select, insert, update, delete on f1.tb_sessao_jogo to authenticated;
