-- ============================================================================
-- tb_bandeira — catálogo de bandeiras usado no combo de Calendário/Provas e
-- no grid de Classificação Geral, agora gravado no banco em vez de precisar
-- alterar código (src/lib/flags.ts + public/flags/*.png) e fazer novo
-- build/deploy toda vez que surge um GP novo (ex.: uma prova em país que
-- ainda não tinha bandeira cadastrada).
--
-- url_imagem guarda a URL pública completa da imagem (fica assim mais simples
-- pro front-end, que só usa <img src={url_imagem}>). As bandeiras que já
-- existiam antes desta migration (public/flags/*.png, cadastradas em
-- src/lib/flags.ts) são inseridas abaixo apontando pra esse mesmo caminho
-- estático — continuam funcionando sem precisar reenviar os PNGs. Dali em
-- diante, novas bandeiras são cadastradas pela tela "Bandeiras" do app, que
-- faz upload da imagem pro Supabase Storage (bucket "bandeiras") e grava a
-- URL pública gerada aqui.
-- ============================================================================

create table if not exists f1.tb_bandeira (
  id         bigint generated by default as identity primary key,
  codigo     text not null unique,
  nome       text not null,
  url_imagem text not null,
  created_at timestamptz not null default now()
);

comment on table f1.tb_bandeira is 'Catálogo de bandeiras (código + nome + URL da imagem), usado no calendário de provas e no grid de Classificação Geral.';

alter table f1.tb_bandeira enable row level security;

drop policy if exists auth_all_tb_bandeira on f1.tb_bandeira;
create policy auth_all_tb_bandeira on f1.tb_bandeira for all to authenticated using (true) with check (true);

grant usage on schema f1 to authenticated;
grant select, insert, update, delete on f1.tb_bandeira to authenticated;
grant usage, select on all sequences in schema f1 to authenticated;

